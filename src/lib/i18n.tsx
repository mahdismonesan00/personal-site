const DICTS: Record<Lang, Dict> = {
  fa: { ...fa, ...EXTRA.fa },
  en: { ...en, ...EXTRA.en },
  ar: { ...ar, ...EXTRA.ar },
  zh: { ...zh, ...EXTRA.zh },
};
const LOCALES: Record<Lang, string> = { fa: "fa-IR", en: "en-US", ar: "ar-EG", zh: "zh-CN" };

type Ctx = {
  lang: Lang;
  dir: "rtl" | "ltr";
  setLang: (l: Lang) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
  pick: (l: Loc) => string;
  fmt: (n: number) => string;
};

const I18nContext = createContext<Ctx | null>(null);
const LANG_KEY = "mm.lang";

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    if (typeof window === "undefined") return "fa";
    const saved = window.localStorage.getItem(LANG_KEY) as Lang | null;
    return saved && DICTS[saved] ? saved : "fa";
  });

  const dir = lang === "fa" || lang === "ar" ? "rtl" : "ltr";

  useEffect(() => {
    const root = document.documentElement;
    root.lang = lang;
    root.dir = dir;
    try {
      window.localStorage.setItem(LANG_KEY, lang);
    } catch {
      /* storage blocked */
    }
  }, [lang, dir]);

  const t = useCallback(
    (key: string, vars?: Record<string, string | number>) => {
      let s = DICTS[lang][key] ?? DICTS.en[key] ?? key;
      if (vars) for (const k of Object.keys(vars)) s = s.replace(new RegExp(`\\{${k}\\}`, "g"), String(vars[k]));
      return s;
    },
    [lang],
  );

  const pick = useCallback((l: Loc) => l[lang] ?? l.en, [lang]);
  const fmt = useCallback((n: number) => new Intl.NumberFormat(LOCALES[lang]).format(n), [lang]);

  const value = useMemo(
    () => ({ lang, dir: dir as "rtl" | "ltr", setLang: setLangState, t, pick, fmt }),
    [lang, dir, t, pick, fmt],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider");
  return ctx;
}